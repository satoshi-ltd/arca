const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const unitless = new Set(["iconStroke"]);
const px = (value) => (typeof value === "number" ? `${value}px` : value);
const declare = (prefix, entries) =>
  entries
    .map(
      ([name, value]) =>
        `  --${prefix}${kebab(name)}: ${typeof value === "number" && !unitless.has(name) ? `${value}px` : value};`,
    )
    .join("\n");
const lines = (entries) => entries.map(([name, value]) => `  --${name}: ${value};`).join("\n");

export function mobileTokens() {
  return `/* Generated by design/build.js from packages/core/design-tokens.js; do not edit. */
:root {
${declare("m-", Object.entries(palettes.light))}
${declare("m-", Object.entries(geometry))}
}
[data-theme="dark"] {
${declare("m-", Object.entries(palettes.dark))}
}
`;
}

