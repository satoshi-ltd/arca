const themeColors = (theme) => [
  ...colorNames.map(([name, key]) => [name, palettes[theme][key]]),
  ...Object.entries(desktopColors[theme]),
];
const changed = (entries, base) => {
  const known = new Map(base);
  return entries.filter(([name, value]) => known.get(name) !== value);
};

